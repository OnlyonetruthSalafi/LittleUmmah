import sharp from 'sharp';
import { writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const src='public/games/coin-box/island.png';
const {data,info}=await sharp(src).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const points=[];
// The slot is the only opaque dark brown feature in the upper quarter.
for(let y=0;y<info.height/4;y++) for(let x=0;x<info.width;x++) {
 const k=(y*info.width+x)*4; if(data[k+3]>240 && data[k]<90 && data[k+1]<55 && data[k+2]<40) points.push([x,y]);
}
const bounds={left:Math.min(...points.map(p=>p[0])),right:Math.max(...points.map(p=>p[0])),top:Math.min(...points.map(p=>p[1])),bottom:Math.max(...points.map(p=>p[1]))};
const slot={x:(bounds.left+bounds.right)/2/info.width*100,y:(bounds.top+bounds.bottom)/2/info.height*100,w:(bounds.right-bounds.left)/info.width*100};
await writeFile('src/features/games/data/coinBoxArt.ts',`// Generated by scripts/prepare-coin-box-art.mjs from the dark slot pixels.\nexport const COIN_SLOT = ${JSON.stringify(slot)};\n`);
const scans=[];
for(const name of ['island','coin','tray']) {
 const {data,info}=await sharp(`public/games/coin-box/${name}.webp`).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 let clear=0,partial=0,solid=0; for(let k=3;k<data.length;k+=4) {if(data[k]===0)clear++;else if(data[k]===255)solid++;else partial++;}
 scans.push({name,width:info.width,height:info.height,clear,partial,solid,centerAlpha:data[(Math.floor(info.height/2)*info.width+Math.floor(info.width/2))*4+3]});
}
await writeFile('output/g-1/alpha-and-slot.json',JSON.stringify({bounds,slot,scans},null,2));
await sharp(src).resize(640).webp({quality:88}).toFile('public/games/hub/coin-box.webp');
const manifest=JSON.parse(await readFile('scripts/source-images.json','utf8'));
manifest['public/games/hub/coin-box.png']=createHash('sha256').update(await readFile(src)).digest('hex');
await writeFile('scripts/source-images.json',JSON.stringify(manifest,null,2)+'\n');
console.log({bounds,slot,scans});
